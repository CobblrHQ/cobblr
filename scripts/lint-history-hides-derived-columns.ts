#!/usr/bin/env tsx
// A column Postgres generates (GENERATED ALWAYS AS) is one of the contract's DERIVED_FIELDS, so a record's History, the activity feed and Cobb's read never show it as a change a person made, or the lint names why it is exempt.
//
// THE BUG THIS PREVENTS. #5863 (2026-10-11): an ordinary note edit showed
// "Search blob: …" and "Measures key: 72da… → af3f…" under the Notes change
// in a record's History. Both are columns Postgres works out from the part's
// text; the update hands the log the row as it now is, so every generated
// column whose value moved looked like a field the person had changed. The
// fix is one rule in packages/platform-contract/src/activity-changes.ts
// (INTERNAL_FIELDS, DERIVED_FIELDS half) that the log, History, the feed and
// Cobb's read all go through. A generated column added later reaches the log
// the same way, so this holds every one to that list.
//
// THE RULE. Every `<column> … GENERATED ALWAYS AS` in a migration (modules/*
// and api, any case, the name on the same line or on the `add column` line
// above) names a column in DERIVED_FIELDS, or sits in EXEMPT below with the
// reason it can never reach a record's History. Migrations are immutable once
// merged, so the exemption lives here, never as a comment in the migration.
//
// THE BOUNDARY, AND WHICH FALSE POSITIVE DREW IT. inventory_stock.shape is
// generated from the stock config, but inventory_stock is not a record with a
// History of its own, and `shape` is a name a person's own field may carry on
// another kind: putting it on the list would hide that person's real edit.
// The rule judges generated columns only; a column a heal pass derives
// (measures, measures_for) is on the list by hand, since nothing in a
// migration says it is derived.
//
// PROVEN RED with search_blob and measures_key taken off DERIVED_FIELDS: two
// violations, at modules/inventory/migrations/0005_search_perf.sql and
// 0013_measure_readings.sql; green with them on.
//
//   npx tsx scripts/lint-history-hides-derived-columns.ts   (pnpm lint history-hides-derived-columns)
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { onlyChanged } from "./lib/lint-only-files.ts";

/** Where the rule bites: the migrations, the only place a column is made. */
const ROOTS = ["modules", "api"];
const CONTRACT = "packages/platform-contract/src/activity-changes.ts";

/** Generated columns that never reach a record's History, each with why. */
const EXEMPT: Record<string, string> = {
  "inventory_stock.shape": "inventory_stock is a part's stock config, not a record with its own History, and `shape` is a name a person's field may carry on another kind",
};

const DERIVED = (() => {
  const m = readFileSync(CONTRACT, "utf8").match(/export const DERIVED_FIELDS[^=]*=\s*new Set\(\[([^\]]*)\]\)/);
  if (!m) throw new Error(`${CONTRACT} no longer exports DERIVED_FIELDS as a Set literal; this lint reads the list from there`);
  return new Set([...m[1]!.matchAll(/"([^"]+)"/g)].map((x) => x[1]!));
})();

interface Violation {
  file: string;
  line: number;
  what: string;
}

function* walk(dir: string): Generator<string> {
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return;
  }
  for (const name of names) {
    if (name === "node_modules" || name === "dist" || name.startsWith(".")) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (/\.sql$/.test(name) && /\/migrations\//.test(p)) yield p;
  }
}

const TABLE = /\b(?:create\s+table(?:\s+if\s+not\s+exists)?|alter\s+table(?:\s+if\s+exists)?)\s+"?([a-z_][a-z0-9_]*)"?/i;
const SAME_LINE = /"?([a-z_][a-z0-9_]*)"?\s+[a-z][a-z0-9_ ]*?(?:\([^)]*\))?\s+generated\s+always\s+as\b/i;
const ADD_COLUMN = /add\s+column(?:\s+if\s+not\s+exists)?\s+"?([a-z_][a-z0-9_]*)"?/i;

function check(file: string, src: string): Violation[] {
  const out: Violation[] = [];
  const lines = src.split("\n");
  let table = "";
  for (let i = 0; i < lines.length; i++) {
    const line = (lines[i] ?? "").replace(/--.*$/, "");
    const t = TABLE.exec(line);
    if (t) table = t[1]!.toLowerCase();
    if (!/generated\s+always\s+as\b/i.test(line) || /identity/i.test(line)) continue;
    let column = (ADD_COLUMN.exec(line) ?? SAME_LINE.exec(line))?.[1];
    for (let j = i - 1; !column && j >= Math.max(0, i - 3); j--) column = ADD_COLUMN.exec(lines[j] ?? "")?.[1];
    if (!column) {
      out.push({ file, line: i + 1, what: "a generated column whose name this lint cannot read; name it on the same line or on the add column line above" });
      continue;
    }
    column = column.toLowerCase();
    if (DERIVED.has(column) || EXEMPT[`${table}.${column}`]) continue;
    out.push({
      file,
      line: i + 1,
      what: `${table}.${column} is generated by Postgres but not in DERIVED_FIELDS (${CONTRACT}): every change to the text it is worked out from would show it in the record's History as a change the person made. Add it there, or to EXEMPT here with why it never reaches a History`,
    });
  }
  return out;
}

const violations: Violation[] = [];
for (const root of ROOTS) for (const file of walk(root)) if (onlyChanged(file)) violations.push(...check(file, readFileSync(file, "utf8")));

if (violations.length) {
  console.error(`lint:history-hides-derived-columns - ${violations.length} violation(s):`);
  for (const v of violations) console.error(`  ${v.file}:${v.line}  ${v.what}`);
  console.error("Fix the violation; a genuine exception opts out with an annotation that carries its reason.");
  process.exit(1);
}
console.log(`lint:history-hides-derived-columns OK`);
