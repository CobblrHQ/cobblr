#!/usr/bin/env node
// Codegen for the built-in DETECTOR list. Mirrors the edge-bridge driver
// refactor (scripts/gen-builtins.mjs): each detector is a self-contained folder
// under src/detectors/<key>/index.ts that exports a `builtin` descriptor. This
// scans for those folders PRESENT ON DISK and emits src/detectors/
// builtins.generated.ts with STATIC imports of only the ones found. Static
// imports mean tsc/esbuild still bundle them; "only what's present" means a
// held-back (deleted) detector folder is simply not wired — no build break.
// That's what lets a distribution ship a vetted SUBSET of detectors (e.g. omit
// the AGPL/GPL manifests) just by omitting folders.
//
// Runs before typecheck/build (see package.json pretypecheck/prebuild). Unlike
// the edge-bridge (which is always BUILT before use), the digifab module is
// imported as SOURCE by the api vitest job — so the generated file is COMMITTED,
// not gitignored, and must stay in sync: regenerate + commit it when you add or
// remove a detector folder (any typecheck/build regenerates it for you).
//
// `--check` mode (CI): regenerate in memory and compare to the COMMITTED file
// (git show HEAD:…) WITHOUT writing. Exit non-zero on any drift. This closes
// the one hole the self-heal-on-typecheck can't: the api vitest lane imports
// the committed file directly and never runs this codegen, so a folder edited
// without a re-commit would silently test against a stale registry.
//
// Why HEAD and not the working tree: CI's typecheck step runs earlier in the
// SAME job and its pretypecheck fires `gen`, rewriting the working-tree file —
// a working-tree compare would be fresh-vs-fresh and could never fail. HEAD is
// what the api vitest lane actually checks out, so HEAD is what must be in sync.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DETECTORS = join(HERE, "..", "src", "detectors");
const OUT = join(DETECTORS, "builtins.generated.ts");
const CHECK = process.argv.includes("--check");

const entries = readdirSync(DETECTORS, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .filter((name) => {
    const idx = join(DETECTORS, name, "index.ts");
    return existsSync(idx) && /export\s+const\s+builtin\b/.test(readFileSync(idx, "utf8"));
  })
  .sort();

const imports = entries.map((n, i) => `import { builtin as b${i} } from "./${n}/index.js";`).join("\n");
const list = entries.map((_, i) => `b${i}`).join(", ");

const generated = `// AUTO-GENERATED by scripts/gen-detectors.mjs — DO NOT EDIT.
// The detector folders present on disk, wired for the registry. Regenerated
// before every build/typecheck; an absent (held-back) detector is just omitted.
import type { DetectorPackage } from "./types.js";
${imports}

export const BUILTINS: DetectorPackage[] = [${list}];
`;

if (CHECK) {
  // The COMMITTED content — not the working tree, which an earlier typecheck's
  // pretypecheck→gen may have already rewritten (see header comment).
  let committed;
  try {
    const repoRoot = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd: HERE, encoding: "utf8" }).trim();
    const relPath = relative(repoRoot, OUT).split("\\").join("/");
    committed = execFileSync("git", ["show", `HEAD:${relPath}`], { cwd: repoRoot, encoding: "utf8" });
  } catch {
    // Not a git checkout (e.g. a source tarball) — fall back to the file on disk.
    committed = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  }
  if (committed !== generated) {
    console.error(
      "gen-detectors --check: the COMMITTED builtins.generated.ts is STALE vs the detector folders on disk.\n" +
        "  Run `pnpm --filter @cobblr/digifab gen` (or any digifab typecheck/build) and COMMIT the result.\n" +
        `  Detector folders found: ${entries.join(", ") || "(none)"}`,
    );
    process.exit(1);
  }
  console.log(`gen-detectors --check: OK — ${entries.length} detector(s) in sync with HEAD.`);
} else {
  writeFileSync(OUT, generated);
  console.log(`gen-detectors: wired ${entries.length} detector(s): ${entries.join(", ") || "(none)"}`);
}
