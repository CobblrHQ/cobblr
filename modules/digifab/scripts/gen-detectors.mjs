#!/usr/bin/env node
// Codegen for the built-in DETECTOR list. Mirrors the edge-bridge driver
// refactor (scripts/gen-builtins.mjs): each detector is a self-contained folder
// under src/detectors/<key>/index.ts that exports a `builtin` descriptor. This
// scans for those folders PRESENT ON DISK and emits src/detectors/
// builtins.generated.ts with STATIC imports of only the ones found. Static
// imports mean tsc/esbuild still bundle them; "only what's present" means a
// held-back (deleted) detector folder is simply not wired — no build break.
// That's what lets a distribution ship a vetted SUBSET of detectors (e.g. omit
// the AGPL/GPL manifests) just by omitting folders.
//
// Runs before typecheck/build (see package.json pretypecheck/prebuild). Unlike
// the edge-bridge (which is always BUILT before use), the digifab module is
// imported as SOURCE by the api vitest job — so the generated file is COMMITTED,
// not gitignored, and must stay in sync: regenerate + commit it when you add or
// remove a detector folder (any typecheck/build regenerates it for you).

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DETECTORS = join(HERE, "..", "src", "detectors");
const OUT = join(DETECTORS, "builtins.generated.ts");

const entries = readdirSync(DETECTORS, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .filter((name) => {
    const idx = join(DETECTORS, name, "index.ts");
    return existsSync(idx) && /export\s+const\s+builtin\b/.test(readFileSync(idx, "utf8"));
  })
  .sort();

const imports = entries.map((n, i) => `import { builtin as b${i} } from "./${n}/index.js";`).join("\n");
const list = entries.map((_, i) => `b${i}`).join(", ");

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/gen-detectors.mjs — DO NOT EDIT.
// The detector folders present on disk, wired for the registry. Regenerated
// before every build/typecheck; an absent (held-back) detector is just omitted.
import type { DetectorPackage } from "./types.js";
${imports}

export const BUILTINS: DetectorPackage[] = [${list}];
`,
);
console.log(`gen-detectors: wired ${entries.length} detector(s): ${entries.join(", ") || "(none)"}`);
