// openai — OpenAI provider. Uses the chat-completions API for chat /
// embed / classify-image / extract-text. Cost is per model from the one
// price table in openai-models.ts.

// EGRESS-FILE: vendor-fixed - the provider's API address, written in the code
import { sendDroppingRefused } from "./refused-params.js";
import { platform, type AiCapability, isChatTurn } from "@cobblr/platform-contract";
import { providerError, providerSentence, reasonFromResponse, reasonFromTransportError, redactSecrets, retryAfterSecOf } from "@cobblr/platform-contract/provider-reason";
import { visionPromptFor } from "./identify-prompt.js";
import { rankImagesPromptFor } from "./rank-images-prompt.js";
import { toolsOf, turnsOf, openAiToolsOf, openAiMessagesOf, parseOpenAiToolCalls } from "./tool-wire.js";
import { promptFingerprint } from "./prompt-fingerprint.js";
import { pricedModel, servedModelOf } from "@cobblr/platform-contract/ai-models";
import { isReasoningModel, openAiCapabilities, openAiCatalog, openAiCostCents } from "./openai-models.js";

// Which models each job may use comes from the key's own listing, read by the
// rules in openai-models.ts (#5417); this is the fallback's view of it.
export const SUPPORTED: Partial<Record<AiCapability, { models: string[]; defaultModel?: string }>> = openAiCapabilities();

function estimateCost(model: string, inputTokens: number, outputTokens: number): number | undefined {
  return openAiCostCents(model, inputTokens, outputTokens) ?? undefined;
}

export function register(): void {
  platform().ai.registerProvider({
    id: "openai",
    label: "OpenAI",
    company: "OpenAI",
    describeCredentials: () => ({
      api_key: { label: "OpenAI API key (sk-…)", secret: true },
    }),
    capabilities: SUPPORTED,
    modelCatalog: openAiCatalog,
    // The prompt this adapter INJECTS (absent from `input` for the image
    // capabilities) joins the cache key — so editing a prompt actually invalidates
    // the replies generated by the old one. See prompt-fingerprint.ts.
    promptFingerprint,
    invoke: async (ctx) => {
      const apiKey = String(ctx.credentials.api_key ?? "");
      if (!apiKey) throw new Error("openai: missing api_key");
      // Every failure carries the reason the provider gave, with the key
      // blanked out of the message (provider-reason.ts).
      const failed = (status: number, body: string) =>
        providerError("openai", reasonFromResponse(status, body), redactSecrets(`openai: ${status} ${body}`, [apiKey]), status, retryAfterSecOf(body));
      switch (ctx.capability) {
        case "embed-text": {
          const text = String(ctx.input.text ?? "");
          const res = await fetch("https://api.openai.com/v1/embeddings", {
            method: "POST",
            headers: {
              "content-type": "application/json",
              authorization: `Bearer ${apiKey}`,
            },
            body: JSON.stringify({ model: ctx.model, input: text }),
          });
          if (!res.ok) throw failed(res.status, await res.text());
          const body = (await res.json()) as {
            data: Array<{ embedding: number[] }>;
            usage: { prompt_tokens: number; total_tokens: number };
            model?: unknown;
          };
          const served = servedModelOf(body.model);
          return {
            result: { vector: body.data[0]?.embedding ?? [] },
            input_tokens: body.usage.prompt_tokens,
            output_tokens: 0,
            cost_cents: estimateCost(pricedModel(ctx.model, served), body.usage.prompt_tokens, 0),
            served_model: served,
          };
        }
        // The builder sends a conversation like chat does (no tools), and reads
        // the answer the same way.
        case "design-workspace":
        case "chat":
        case "plan-changes":
        case "summarise":
        case "classify-image":
        case "split-image":
        case "identify-glance":
        case "document-read":
        case "identify-image":
        case "rank-images":
        case "extract-text":
        case "match-to-catalog": {
          const messages = buildMessages(ctx.capability, ctx.input);
          const body: Record<string, unknown> = {
            model: ctx.model,
            // Extraction/routing surfaces want determinism (see the Anthropic
            // adapter note); config can opt back into sampling spread.
            // A reasoning model (gpt-5, o-series) refuses any temperature but
            // its own, so it is sent none unless config asks.
            ...(typeof ctx.config.temperature === "number" ? { temperature: ctx.config.temperature } : isReasoningModel(ctx.model) ? {} : { temperature: 0 }),
            messages,
          };
          // Native tool-calling for chat: forward the neutral tool defs.
          const toolDefs = isChatTurn(ctx.capability) ? toolsOf(ctx.input) : null;
          if (toolDefs) body.tools = openAiToolsOf(toolDefs);
          if (
            ctx.capability === "classify-image" ||
            (ctx.capability === "identify-image" || ctx.capability === "document-read" || ctx.capability === "split-image" || ctx.capability === "identify-glance") ||
            ctx.capability === "rank-images" ||
            ctx.capability === "match-to-catalog"
          ) {
            body.response_format = { type: "json_object" };
          }
          // The caller's own shape (#5790) holds the model to it exactly.
          const outputSchema = (ctx.input as Record<string, unknown>).output_schema;
          if (outputSchema && typeof outputSchema === "object" && !Array.isArray(outputSchema)) {
            body.response_format = { type: "json_schema", json_schema: { name: "cobblr_output", schema: outputSchema } };
          }
          // A model that refuses an optional knob (temperature on a reasoning
          // model) is sent again without it, and remembered (refused-params.ts).
          const res = await sendDroppingRefused("openai", ctx.model, body, (b) =>
            fetch("https://api.openai.com/v1/chat/completions", {
              method: "POST",
              headers: {
                "content-type": "application/json",
                authorization: `Bearer ${apiKey}`,
              },
              body: JSON.stringify(b),
            }),
          );
          if (!res.ok) throw failed(res.status, await res.text());
          const out = (await res.json()) as {
            choices: Array<{
              message: {
                role: string;
                content: string | null;
                tool_calls?: Array<{ id?: string; function?: { name?: string; arguments?: unknown } }>;
              };
            }>;
            usage: { prompt_tokens: number; completion_tokens: number };
            model?: unknown;
          };
          const served = servedModelOf(out.model);
          const msg = out.choices[0]?.message ?? { role: "assistant", content: "" };
          const calls = parseOpenAiToolCalls(msg);
          return {
            result: {
              role: msg.role ?? "assistant",
              content: msg.content ?? "",
              ...(calls ? { tool_calls: calls } : {}),
            },
            input_tokens: out.usage.prompt_tokens,
            output_tokens: out.usage.completion_tokens,
            cost_cents: estimateCost(pricedModel(ctx.model, served), out.usage.prompt_tokens, out.usage.completion_tokens),
            served_model: served,
          };
        }
        default:
          throw new Error(`openai: capability ${ctx.capability} not implemented`);
      }
    },
    testConnection: async (credentials) => {
      const apiKey = String(credentials.api_key ?? "");
      if (!apiKey || !apiKey.startsWith("sk-")) {
        return { ok: false, error: "api_key looks malformed (expected sk-…)" };
      }
      try {
        const res = await fetch("https://api.openai.com/v1/models", {
          headers: { authorization: `Bearer ${apiKey}` },
        });
        if (res.ok) return { ok: true };
        const body = await res.text().catch(() => "");
        const reason = reasonFromResponse(res.status, body);
        return { ok: false, reason, error: providerSentence(reason, { provider: "openai", retryAfterSec: retryAfterSecOf(body) }) };
      } catch (err) {
        const reason = reasonFromTransportError(err);
        return { ok: false, reason, error: providerSentence(reason, { provider: "openai" }), detail: redactSecrets((err as Error).message, [apiKey]) };
      }
    },
  });
}

export function buildMessages(
  capability: AiCapability,
  input: Record<string, unknown>,
): Array<{ role: string; content: unknown }> {
  switch (capability) {
    case "summarise": {
      const text = String(input.text ?? "");
      const lengthHint = String(input.lengthHint ?? "3 sentences");
      return [
        { role: "system", content: `Summarise in ${lengthHint}. Plain prose, no preamble.` },
        { role: "user", content: text },
      ];
    }
    case "classify-image": {
      const prompt = String(input.prompt ?? "Classify this image with one of the supplied labels.");
      const labels = (input.labels as string[]) ?? [];
      const imageUrl = typeof input.image_url === "string" ? input.image_url : null;
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      const content: Array<Record<string, unknown>> = [
        {
          type: "text",
          // A caller's own shape replaces the labels form (#5790).
          text: input.output_schema
            ? prompt
            : `${prompt}\n\nAllowed labels: ${labels.join(", ")}\n` +
              `Return JSON shaped as {"labels": [{"label": string, "confidence": number}]} ordered desc.`,
        },
      ];
      if (imageUrl) content.push({ type: "image_url", image_url: { url: imageUrl } });
      else if (imageB64) {
        content.push({
          type: "image_url",
          image_url: { url: `data:image/png;base64,${imageB64}` },
        });
      }
      return [{ role: "user", content }];
    }
    case "split-image":
    case "identify-glance":
    case "document-read":
    case "identify-image": {
      const mediaType = String(input.image_media_type ?? "image/jpeg");
      const imageUrl = typeof input.image_url === "string" ? input.image_url : null;
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      // identifyPromptFor honours a caller-supplied `input.prompt` (detectSplitItems'
      // "find and box each distinct thing"), which this branch used to IGNORE — so
      // that call asked the identify question, got no `items` back, and was wasted
      // on every single split. The edge-bridge adapter always honoured it.
      const content: Array<Record<string, unknown>> = [{ type: "text", text: visionPromptFor(capability, input) }];
      if (imageUrl) content.push({ type: "image_url", image_url: { url: imageUrl } });
      else if (imageB64) {
        content.push({ type: "image_url", image_url: { url: `data:${mediaType};base64,${imageB64}` } });
      }
      return [{ role: "user", content }];
    }
    case "rank-images": {
      // ONE image: a numbered contact sheet of the candidates (composed by
      // core-scan). It used to be N attachments, which needed multi-image
      // support three of the five adapters didn't have — so the capability was
      // dark on exactly the providers real workspaces use. Same single-image
      // shape as identify-image now. rankImagesPromptFor is the SAME resolver
      // the fingerprint keys on.
      const mediaType = String(input.image_media_type ?? "image/jpeg");
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      const content: Array<Record<string, unknown>> = [{ type: "text", text: rankImagesPromptFor(input) }];
      if (imageB64) {
        content.push({ type: "image_url", image_url: { url: `data:${mediaType};base64,${imageB64}` } });
      }
      return [{ role: "user", content }];
    }
    case "extract-text": {
      const imageUrl = typeof input.image_url === "string" ? input.image_url : null;
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      const content: Array<Record<string, unknown>> = [
        { type: "text", text: "Read all text from this image. Return the text only." },
      ];
      if (imageUrl) content.push({ type: "image_url", image_url: { url: imageUrl } });
      else if (imageB64) {
        content.push({
          type: "image_url",
          image_url: { url: `data:image/png;base64,${imageB64}` },
        });
      }
      return [{ role: "user", content }];
    }
    case "match-to-catalog": {
      const userEntity = input.user_entity;
      const candidates = input.candidates;
      const imageUrl = typeof input.image_url === "string" ? input.image_url : null;
      const text =
        `You're matching a user's entity to a catalog. Pick the best match.\n` +
        `User entity:\n${JSON.stringify(userEntity, null, 2)}\n\n` +
        `Candidates:\n${JSON.stringify(candidates, null, 2)}\n\n` +
        `Return JSON: {"matches": [{"candidate_id": string, "confidence": number}]} ordered desc, top 3.`;
      const content: Array<Record<string, unknown>> = [{ type: "text", text }];
      if (imageUrl) content.push({ type: "image_url", image_url: { url: imageUrl } });
      return [{ role: "user", content }];
    }
    // The builder sends a conversation like chat does (no tools), and reads
    // the answer the same way.
    case "design-workspace":
    case "chat":
    case "plan-changes":
    default: {
      // Tool-aware turn mapping (assistant tool_calls / role:"tool" results) —
      // OpenAI's dialect of the neutral wire; see tool-wire.ts.
      const msgs = openAiMessagesOf(turnsOf(input)) as Array<{ role: string; content: unknown }>;
      // Honour a first-class `system` prompt (chat.ts passes it here, not as a
      // role:"system" message) by prepending it as the system turn.
      const system = typeof input.system === "string" ? input.system : undefined;
      return system ? [{ role: "system", content: system }, ...msgs] : msgs;
    }
  }
}
