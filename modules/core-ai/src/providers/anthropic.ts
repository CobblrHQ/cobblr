// Which models each job may use is no longer a list here: the key's own
// listing, read by the rules in anthropic-models.ts (#5417). This is what a
// surface with no listing at hand offers, and each job's default: a family's
// latest, which the platform turns into the newest listed model per call.
export const SUPPORTED: Partial<Record<AiCapability, { models: string[]; defaultModel?: string }>> = anthropicCapabilities();

interface ClaudeContentBlock {
  type: "text" | "image";
  text?: string;
  source?: { type: "base64"; media_type: string; data: string };
}

export function register(): void {
  platform().ai.registerProvider({
    id: "anthropic",
    label: "Anthropic (Claude)",
    company: "Anthropic",
    describeCredentials: () => ({
      api_key: { label: "API key (usually starts with sk-ant-)", secret: true },
    }),
    // Paid, so it sits below the two free options rather than above them.
    rank: 30,
    setup: {
      summary:
        "Paid, billed per use. Strong at reading labels and handwriting. " +
        "A Claude.ai subscription is a different thing and does not work here: this needs " +
        "an API key, which is topped up separately.",
      steps: [
        { text: "Open the Anthropic Console and sign in or sign up.", href: "https://console.anthropic.com/settings/keys" },
        { text: 'Add credit under Billing first. A brand new account has none, and a key without credit fails on the first use.' },
        { text: 'Go to API keys, click "Create Key", and give it any name.' },
        { text: "Copy the key. It starts with sk-ant- and is shown once." },
        { text: "Paste it below and save." },
      ],
    },
    capabilities: SUPPORTED,
    modelCatalog: anthropicCatalog,
    // The prompt this adapter INJECTS (absent from `input` for the image
    // capabilities) joins the cache key — so editing a prompt actually invalidates
    // the replies generated by the old one. See prompt-fingerprint.ts.
    promptFingerprint,
    invoke: async (ctx) => callAnthropic({ apiKey: String(ctx.credentials.api_key ?? ""), model: ctx.model, capability: ctx.capability, input: ctx.input, config: ctx.config }),
    testConnection: async (credentials) => {
      const apiKey = String(credentials.api_key ?? "");
      if (!apiKey || !apiKey.startsWith("sk-ant-")) {
        return { ok: false, reason: "invalid_key", error: "api_key looks malformed (expected sk-ant-…)" };
      }
      // A real probe, the cheapest there is: the models list needs the key and
      // spends nothing. A prefix check alone saved a mistyped key as ready.
      try {
        const res = await fetch("https://api.anthropic.com/v1/models", {
          headers: { "x-api-key": apiKey, "anthropic-version": "2023-06-01" },
        });
        if (res.ok) return { ok: true };
        const body = await res.text().catch(() => "");
        const reason = reasonFromResponse(res.status, body);
        return { ok: false, reason, error: providerSentence(reason, { provider: "anthropic", retryAfterSec: retryAfterSecOf(body) }) };
      } catch (err) {
        const reason = reasonFromTransportError(err);
        return { ok: false, reason, error: providerSentence(reason, { provider: "anthropic" }), detail: redactSecrets((err as Error).message, [apiKey]) };
      }
    },
  });
}

/** The system prompt the Messages API takes, gathered from input.system and
 *  every role:"system" turn in order, and the turns left to send. */
export function anthropicSystemOf(input: Record<string, unknown>): { system: string | undefined; turns: ReturnType<typeof turnsOf> } {
  const all = turnsOf(input);
  const parts = [typeof input.system === "string" ? input.system : "", ...all.filter((t) => t.role === "system").map((t) => (typeof t.content === "string" ? t.content : ""))]
    .map((t) => t.trim())
    .filter(Boolean);
  return { system: parts.length ? parts.join("\n\n") : undefined, turns: all.filter((t) => t.role !== "system") };
}

/** The request body's messages and system for a job: exported so a test can
 *  hold the wire shape to what the API accepts. */
export function anthropicRequestOf(capability: AiCapability, input: Record<string, unknown>) {
  return buildMessages(capability, input);
}

function buildMessages(
  capability: AiCapability,
  input: Record<string, unknown>,
): { system?: string; messages: Array<{ role: string; content: ClaudeContentBlock[] }> } {
  switch (capability) {
    case "summarise": {
      const text = String(input.text ?? "");
      const lengthHint = String(input.lengthHint ?? "3 sentences");
      return {
        system: `Summarise in ${lengthHint}. Plain prose, no preamble.`,
        messages: [{ role: "user", content: [{ type: "text", text }] }],
      };
    }
    case "classify-image": {
      const prompt = String(input.prompt ?? "Classify this image with one of the supplied labels.");
      const labels = (input.labels as string[]) ?? [];
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      const mediaType = String(input.image_media_type ?? "image/png");
      const content: ClaudeContentBlock[] = [];
      if (imageB64) {
        content.push({
          type: "image",
          source: { type: "base64", media_type: mediaType, data: imageB64 },
        });
      }
      content.push({
        type: "text",
        // A caller that names its own shape (a receipt photo) asked for that
        // shape alone; the labels form would contradict it (#5790).
        text: input.output_schema
          ? prompt
          : `${prompt}\n\nAllowed labels: ${labels.join(", ")}\n` +
            `Reply with JSON shaped {"labels": [{"label": string, "confidence": number}]} ordered desc. JSON only.`,
      });
      return { messages: [{ role: "user", content }] };
    }
    case "split-image":
    case "identify-glance":
    case "document-read":
    case "identify-image": {
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      const mediaType = String(input.image_media_type ?? "image/jpeg");
      const content: ClaudeContentBlock[] = [];
      if (imageB64) {
        content.push({ type: "image", source: { type: "base64", media_type: mediaType, data: imageB64 } });
      }
      // identifyPromptFor honours a caller-supplied `input.prompt` (detectSplitItems'
      // "find and box each distinct thing"), which this branch used to IGNORE — so
      // that call asked the identify question, got no `items` back, and was wasted
      // on every single split. The edge-bridge adapter always honoured it.
      content.push({ type: "text", text: visionPromptFor(capability, input) });
      return { messages: [{ role: "user", content }] };
    }
    case "rank-images": {
      // ONE image: the numbered contact sheet (see the openai adapter's note).
      // Image first, then the text — the same order identify-image uses here.
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      const mediaType = String(input.image_media_type ?? "image/jpeg");
      const content: ClaudeContentBlock[] = [];
      if (imageB64) {
        content.push({ type: "image", source: { type: "base64", media_type: mediaType, data: imageB64 } });
      }
      content.push({ type: "text", text: rankImagesPromptFor(input) });
      return { messages: [{ role: "user", content }] };
    }
    case "extract-text": {
      const imageB64 = typeof input.image_b64 === "string" ? input.image_b64 : null;
      const mediaType = String(input.image_media_type ?? "image/png");
      const content: ClaudeContentBlock[] = [];
      if (imageB64) {
        content.push({
          type: "image",
          source: { type: "base64", media_type: mediaType, data: imageB64 },
        });
      }
      content.push({ type: "text", text: "Read all text from the image. Return the text only." });
      return { messages: [{ role: "user", content }] };
    }
    case "match-to-catalog": {
      const userEntity = input.user_entity;
      const candidates = input.candidates;
      return {
        messages: [
          {
            role: "user",
            content: [
              {
                type: "text",
                text:
                  `You're matching a user's entity to a catalog. Pick the best match.\n` +
                  `User entity:\n${JSON.stringify(userEntity, null, 2)}\n\n` +
                  `Candidates:\n${JSON.stringify(candidates, null, 2)}\n\n` +
                  `Reply with JSON: {"matches": [{"candidate_id": string, "confidence": number}]} ordered desc, top 3. JSON only.`,
              },
            ],
          },
        ],
      };
    }
    case "chat":
    case "plan-changes":
    default: {
      // Tool-aware turn mapping: assistant tool_calls → tool_use blocks; tool
      // results → user turns with tool_result blocks (Anthropic's dialect of
      // the neutral wire — see tool-wire.ts).
      // A caller's instructions arrive either as input.system or as a
      // role:"system" turn (the receipt reader, the organizer, the session
      // theme). The Messages API takes them only as its top-level `system`
      // and refuses a system turn with a 400, which failed every such call
      // on a Claude connection (the hosted service, 2026-10-10).
      const { system, turns } = anthropicSystemOf(input);
      const msgs = anthropicMessagesOf(turns) as Array<{ role: string; content: ClaudeContentBlock[] }>;
      return { system, messages: msgs };
    }
  }
}

/** Below this many characters a prefix is under every Claude model's
 *  minimum cacheable length (512 to 4,096 tokens by model), and the marker
 *  would be ignored: it is left off rather than sent for nothing. */
const MIN_CACHED_PREFIX_CHARS = 4000;

type CacheMark = { cache_control?: { type: "ephemeral" } };

/** The Messages API request body for one call, with Cobb's prompt cache
 *  (#5319): tools, then the rules every workspace shares (breakpoint 1),
 *  then this workspace (breakpoint 2), then this person and moment, then the
 *  conversation with a breakpoint on its newest user turn, so each turn
 *  re-reads the ones before it. At most three breakpoints, of the API's four.
 *  A call without `system_blocks` keeps one breakpoint on a long system
 *  prompt, as before. Exported for the managed provider and the tests. */
export function anthropicRequestBody(args: { model: string; capability: AiCapability; input: Record<string, unknown>; config: Record<string, unknown> }): Record<string, unknown> {
  const { model, capability, input, config } = args;
  const { messages, system } = buildMessages(capability, input);
  const body: Record<string, unknown> = {
    model,
    max_tokens: typeof config.max_tokens === "number" ? config.max_tokens : 1024,
    // Every capability this adapter serves is extraction/routing-shaped
    // (the matchmaker literally instructs "identical items must route the
    // same way") — sampling variance is pure downside, so temperature
    // pins to 0 unless a caller/config explicitly asks for spread.
    // Claude 5 and later refuse it ("deprecated for this model"), so it is
    // sent only where a model takes it; a model that refuses it anyway is
    // answered by sendDroppingRefused below.
    ...(typeof config.temperature === "number" ? { temperature: config.temperature } : anthropicTakesTemperature(model) ? { temperature: 0 } : {}),
    messages,
  };
  // Native tool-calling for chat: forward the neutral tool defs.
  const toolDefs = isChatTurn(capability) ? toolsOf(input) : null;
  const tools = toolDefs ? anthropicToolsOf(toolDefs) : null;
  if (tools) body.tools = tools;
  const blocks = systemBlocksOf(input);
  if (blocks) {
    const extra = (system ?? "").startsWith(blocks.text) ? (system ?? "").slice(blocks.text.length).trim() : "";
    const toolChars = tools ? JSON.stringify(tools).length : 0;
    let prefix = toolChars;
    const out: Array<{ type: "text"; text: string } & CacheMark> = [];
    for (const text of [blocks.fixed, blocks.workspace]) {
      if (!text) continue;
      prefix += text.length;
      out.push({ type: "text", text, ...(prefix >= MIN_CACHED_PREFIX_CHARS ? { cache_control: { type: "ephemeral" as const } } : {}) });
    }
    const moment = [blocks.moment, extra].filter(Boolean).join("\n\n");
    if (moment) out.push({ type: "text", text: moment });
    body.system = out;
    if (prefix >= MIN_CACHED_PREFIX_CHARS) markNewestUserTurn(messages);
  } else if (system) {
    // Long static system prompts (the ~2K-token matchmaker block) get a
    // prompt-cache breakpoint: bursty scanning re-bills the fixed prefix
    // on every call otherwise. Below the provider's minimum cacheable
    // length the marker is ignored, so the char gate just avoids noise.
    body.system = system.length > MIN_CACHED_PREFIX_CHARS ? [{ type: "text", text: system, cache_control: { type: "ephemeral" } }] : system;
  }
  return body;
}

/** The prompt's three parts, when the caller sent them (chat, #5319). */
function systemBlocksOf(input: Record<string, unknown>): { fixed: string; workspace: string; moment: string; text: string } | null {
  const b = input.system_blocks;
  if (!Array.isArray(b) || b.length !== 3 || !b.every((x) => typeof x === "string")) return null;
  const [fixed, workspace, moment] = b as [string, string, string];
  return { fixed, workspace, moment, text: typeof input.system === "string" ? input.system.trim() : "" };
}

/** The newest user turn's last block carries the conversation's breakpoint. */
function markNewestUserTurn(messages: Array<{ role: string; content: unknown }>): void {
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i]!;
    if (m.role !== "user") continue;
    if (typeof m.content === "string") m.content = [{ type: "text", text: m.content }];
    const content = m.content as Array<Record<string, unknown>>;
    const last = content[content.length - 1];
    if (last) last.cache_control = { type: "ephemeral" };
    return;
  }
}

export interface AnthropicAnswer {
  result: Record<string, unknown>;
  input_tokens: number;
  output_tokens: number;
  /** Prompt tokens read from the cache, at a tenth of the input price. */
  cache_read_tokens: number;
  /** Prompt tokens written to the cache, at 1.25 times the input price. */
  cache_write_tokens: number;
  cost_cents?: number;
  served_model: string | null;
}

/** One Messages API call: the request (blocks, breakpoints, tools), the
 *  send, and the usage read back, priced. The API key is a parameter, so the
 *  managed provider calls this rather than keeping its own copy. */
export async function callAnthropic(args: { apiKey: string; model: string; capability: AiCapability; input: Record<string, unknown>; config: Record<string, unknown> }): Promise<AnthropicAnswer> {
  const { apiKey, model, capability } = args;
  if (!apiKey) throw new Error("anthropic: missing api_key");
  const body = anthropicRequestBody(args);
  const res = await sendDroppingRefused("anthropic", model, body, (b) =>
    fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": apiKey,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify(b),
    }),
  );
  if (!res.ok) {
    const text = await res.text();
    throw providerError("anthropic", reasonFromResponse(res.status, text), redactSecrets(`anthropic: ${res.status} ${text}`, [apiKey]), res.status, retryAfterSecOf(text));
  }
  const out = (await res.json()) as {
    content: Array<{ type: string; text?: string; id?: string; name?: string; input?: unknown }>;
    usage: { input_tokens: number; output_tokens: number; cache_read_input_tokens?: number | null; cache_creation_input_tokens?: number | null };
    model?: unknown;
  };
  // Priced as the model that answered: a redirected call is billed as
  // the model it was served by, not the one it asked for.
  const served = servedModelOf(out.model);
  const cost = anthropicCostCents(pricedModel(model, served), out.usage);
  const parsed = parseAnthropicContent(out.content);
  const text = parsed.text;
  return {
    result:
      capability === "embed-text"
        ? { vector: [] }
        : isChatTurn(capability)
          ? { role: "assistant", content: text, ...(parsed.tool_calls ? { tool_calls: parsed.tool_calls } : {}) }
          : { text },
    input_tokens: out.usage.input_tokens,
    output_tokens: out.usage.output_tokens,
    cache_read_tokens: out.usage.cache_read_input_tokens ?? 0,
    cache_write_tokens: out.usage.cache_creation_input_tokens ?? 0,
    // A model with no known price logs no cost, never $0 (anthropic-models.ts).
    ...(cost !== null ? { cost_cents: cost } : {}),
    served_model: served,
  };
}
