// What each module's write route changes: the workspace's records, or the
// workspace itself (#7343). A "Look and make changes" token reaches the first
// and never the second, and this is where that is decided, one line a route.
//
// It used to be a deny-list over an open set: any module write was a record
// write unless a pattern named it, so each new module route was open to the
// token until someone remembered it. A public surface, an ESPHome device, a
// bulk machine connection and a station enrolment all were. Now a route no
// list names is refused to the token, and a test walks every module write
// route and fails on one that is not here, or here and gone.
//
// "workspace" is what TOKEN_ACCESS_MEANS.change promises the token never
// touches: settings and defaults, connections and the credentials they hold,
// device and machine enrolment, public links and the tokens behind them, and
// how the assistant answers everyone. Testing a saved connection changes
// nothing and is a record write; so are a bridge's and a station's own calls,
// which run on the device's token.

