/** Another name a module's routes answer at (its manifest's `aliases`). */
export const MODULE_ROUTE_ALIASES: Record<string, string> = {
  "core-library": "core-documents",
};

function matches(template: string[], path: string[]): number {
  if (template.length !== path.length) return -1;
  let literal = 0;
  for (let i = 0; i < path.length; i++) {
    if (template[i] === ":x") continue;
    if (template[i] !== path[i]) return -1;
    literal++;
  }
  return literal;
}

const split = (p: string): string[] => p.split("/").filter(Boolean);

/** What a write to `/modules/<module><rel>` changes, or null when no route of
 *  the module answers it. `rel` is the routed path below the module, lower
 *  case. The most literal template wins, as the router's would; a tie that
 *  includes a workspace route is a workspace write. */
export function moduleWriteChanges(module: string, method: string, rel: string): ModuleWriteChanges | null {
  const entry = MODULE_WRITES[MODULE_ROUTE_ALIASES[module] ?? module];
  if (!entry) return null;
  const verb = method.toUpperCase();
  const path = split(rel);
  let best = -1;
  let found: ModuleWriteChanges | null = null;
  for (const changes of ["records", "workspace"] as const) {
    for (const route of entry[changes]) {
      const [v = "", p = ""] = route.split(" ");
      if (v !== verb) continue;
      const score = matches(split(p.toLowerCase()), path);
      if (score < 0) continue;
      if (score > best || (score === best && changes === "workspace")) {
        best = score;
        found = changes;
      }
    }
  }
  return found;
}
